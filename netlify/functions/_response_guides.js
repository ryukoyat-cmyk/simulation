// tags가 하나라도 겹치면 채택합니다. 특정 요소를 좁혀 찾을 때 씁니다.
export function guidesFor(tags) {
  const wanted = new Set(Array.isArray(tags) ? tags : [tags]);
  return GUIDES.filter((g) => g.tags.some((t) => wanted.has(t)));
}

export function formatCitation(source) {
  const label = source.doc === "A" ? "학교민원 처리 매뉴얼" : "학교 민원 응대 안내자료";
  return `${label} p.${source.page}`;
}
