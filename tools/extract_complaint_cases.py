# -*- coding: utf-8 -*-
"""사례집 PDF(casebook.pdf)에서 민원 사례를 뽑아 Netlify 함수용 모듈로 만든다.

사용법: python3 tools/extract_complaint_cases.py <casebook.pdf> <출력.js>
필요: pip install pymupdf

규칙(모두 PDF 구조에서 나온 것이며 건수를 맞추려는 보정은 하지 않는다)
- "(제목)" 으로 시작하는 줄이 한 사례의 시작이다. 다음 "(제목)" 전까지가 본문이다.
- 본문에 "1. … 2. …" 번호 항목이 둘 이상이면 항목마다 별도 사례로 나눈다(제목에 #번호).
- 줄바꿈은 PDF의 레이아웃 줄바꿈이므로, 줄 끝에 공백이 없으면 이어 붙이고 있으면 한 칸으로 합친다.
- 본문 길이를 자르지 않는다. 주제 분류도 하지 않는다.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import pymupdf

HEADER = "초등학교 학부모 교권침해 민원 사례 모음집"
NUMBERED = re.compile(r"(?:(?<=\s)|^)([1-9][0-9]?)\.\s")


def page_lines(doc):
    for page_number, page in enumerate(doc, 1):
        for raw in page.get_text().split("\n"):
            line = raw.replace("​", " ")
            stripped = line.strip()
            if not stripped or stripped == HEADER or re.fullmatch(r"\d+", stripped):
                continue
            yield page_number, line


def merge(lines: list[str]) -> str:
    text = ""
    previous = ""
    for line in lines:
        if not text:
            text = line
        elif re.match(r"\s*[1-9][0-9]?\.\s", line):
            text += "\n" + line
        elif len(previous.strip()) <= 12 and not text.endswith(" "):
            text += " " + line
        else:
            text += line
        previous = line
    return re.sub(r"[ \t]+", " ", re.sub(r" ?\n ?", "\n", text)).strip()


def split_numbered(title: str, body: str, page: int) -> list[dict]:
    starts = [m.start() for m in NUMBERED.finditer(body)]
    seq = [body[s:].lstrip()[: len(str(i + 1)) + 1] for i, s in enumerate(starts)]
    if len(starts) >= 2 and seq[0].startswith("1."):
        pieces = []
        preface = body[: starts[0]].strip()
        if len(preface) >= 40:
            pieces.append({"title": title, "body": preface, "page": page})
        for index, start in enumerate(starts):
            end = starts[index + 1] if index + 1 < len(starts) else len(body)
            piece = body[start:end].strip()
            if len(piece) >= 35:
                pieces.append({"title": f"{title} #{index + 1}", "body": piece, "page": page})
        if pieces:
            return pieces
    return [{"title": title, "body": body, "page": page}]


def extract(pdf_path: Path) -> list[dict]:
    doc = pymupdf.open(str(pdf_path))
    raw: list[dict] = []
    current = None
    pending = None
    for page_number, line in page_lines(doc):
        text = line.lstrip()
        if pending is not None:
            pending[0] += line
            if ")" in line:
                joined = pending[0]
                close = joined.rfind(")")
                current = {"title": joined[1:close], "lines": [joined[close + 1 :]], "page": pending[1]}
                raw.append(current)
                pending = None
            continue
        if text.startswith("("):
            if ")" in text:
                close = text.rfind(")")
                title = text[1:close]
                if 4 <= len(title.strip()) <= 220:
                    current = {"title": title, "lines": [text[close + 1 :]], "page": page_number}
                    raw.append(current)
                    continue
            else:
                pending = [text, page_number]
                continue
        if current is not None:
            current["lines"].append(line)

    cases: list[dict] = []
    seen: set[str] = set()
    for item in raw:
        title = re.sub(r"\s+", " ", item["title"]).strip()
        body = merge(item["lines"])
        for piece in split_numbered(title, body, item["page"]):
            key = re.sub(r"\s+", "", f"{piece['title']}{piece['body']}")[:200]
            if key in seen or len(piece["body"]) < 20:
                continue
            seen.add(key)
            cases.append({"id": f"case-{len(cases) + 1:04d}", "page": piece["page"], "title": piece["title"], "excerpt": piece["body"]})
    return cases


def main() -> int:
    if len(sys.argv) != 3:
        print("Usage: extract_complaint_cases.py <casebook.pdf> <output.js>", file=sys.stderr)
        return 2
    source, output = Path(sys.argv[1]), Path(sys.argv[2])
    cases = extract(source)
    stats = {"sourceReportedTotal": 2077, "extractedCases": len(cases), "sourceName": "초등학교 학부모 교권침해 민원 사례 모음집(casebook.pdf)"}
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        "// Generated by tools/extract_complaint_cases.py. Do not edit by hand.\n"
        f"export const complaintCaseStats = {json.dumps(stats, ensure_ascii=False, indent=2)};\n\n"
        f"export const complaintCases = {json.dumps(cases, ensure_ascii=False, indent=2)};\n",
        encoding="utf-8",
    )
    print(json.dumps(stats, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
